#!/usr/bin/env python3
"""Writes compiler/driver/pkg/spdx_list.of from the SPDX license list.

The list is data embedded in the compiler (ADR 0081) and updated by hand:
download `json/licenses.json` and `json/exceptions.json` of a release of
https://github.com/spdx/license-list-data, then run

    python3 tools/gen_spdx.py licenses.json exceptions.json
"""

import argparse
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "compiler" / "driver" / "pkg" / "spdx_list.of"


def items(ids, indent):
    """The string literals of `ids`, wrapped at 100 columns."""
    lines = []
    line = indent
    for name in ids:
        word = '"{}",'.format(name)
        if len(line) + len(word) + 1 > 100 and line.strip():
            lines.append(line.rstrip())
            line = indent
        line += word + " "
    lines.append(line.rstrip())
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("licenses")
    parser.add_argument("exceptions")
    args = parser.parse_args()
    licenses = json.loads(pathlib.Path(args.licenses).read_text())
    exceptions = json.loads(pathlib.Path(args.exceptions).read_text())
    version = licenses["licenseListVersion"]
    ids = sorted(item["licenseId"] for item in licenses["licenses"])
    exc = sorted(item["licenseExceptionId"] for item in exceptions["exceptions"])
    text = """/**
 * @module
 * The SPDX license list {version} (ADR 0081), generated by
 * `tools/gen_spdx.py`: do not edit.
 */

/** The version of the SPDX license list. */
pub const SPDX_LIST_VERSION: str = "{version}"

/** The license identifiers, sorted. */
pub fn licenseIds() List<str> {{
    return [
{ids}
    ]
}}

/** The exception identifiers, sorted. */
pub fn exceptionIds() List<str> {{
    return [
{exc}
    ]
}}
""".format(version=version, ids=items(ids, " " * 8), exc=items(exc, " " * 8))
    OUT.write_text(text)


if __name__ == "__main__":
    main()
