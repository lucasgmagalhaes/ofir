def intrinsics(t: str, ops: list[tuple[str, int]]) -> str:
    lines = ["// The operations the compiler generates for this type (ADR 0019).",
             'extern "intrinsic" {']
    for op, arity in ops:
        params = ", ".join(f"{p}: {t}" for p in "ab"[:arity])
        lines.append(f"    fn {op}_{t}({params}) {t}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def module_doc(t: str) -> str:
    return f"/**\n * @module\n * The methods of `{t}` (docs/std/core.md).\n */\n\n"


def int_file(t: str) -> str:
    bits = BITS[t]
    signed = t in SIGNED
    lo = -(1 << (bits - 1)) if signed else 0
    hi = (1 << (bits - 1)) - 1 if signed else (1 << bits) - 1
    alias = {"i64": " (`int`)", "u64": " (`uint`)"}.get(t, "")
    abs_text = (SIGNED_ABS if signed else UNSIGNED_ABS).format(t=t)
    checked = (SIGNED_CHECKED if signed else UNSIGNED_CHECKED).format(t=t)
    parse = INT_PARSE.format(t=t, plus=" or `+`",
                             negative_check="" if signed else " || negative")
    body = INT.format(t=t, abs=abs_text, checked=checked, parse=parse, bits=bits, alias=alias,
                      min=lo, max=hi,
                      desc=f"{bits}-bit {'signed' if signed else 'unsigned'}")
    ops = [("wrapping_add", 2), ("wrapping_sub", 2), ("wrapping_mul", 2)]
    return module_doc(t) + GENERATED + intrinsics(t, ops) + body


def float_file(t: str) -> str:
    alias = " (`float`)" if t == "f64" else ""
    ops = [("sqrt", 1), ("fabs", 1), ("floor", 1), ("ceil", 1), ("minnum", 2), ("maxnum", 2)]
    c = "d" if t == "f64" else "f"
    return module_doc(t) + GENERATED + intrinsics(t, ops) + "\n" + libm_externs(t, c) + \
        FLOAT.format(t=t, bits=t[1:], alias=alias, c=c, math=math_methods(t))


if __name__ == "__main__":
    OUT.mkdir(parents=True, exist_ok=True)
    for t in SIGNED + UNSIGNED:
        (OUT / f"{t}.of").write_text(int_file(t))
    for t in FLOATS:
        (OUT / f"{t}.of").write_text(float_file(t))
